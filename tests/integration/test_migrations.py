"""Migrations must be reversible and match the models. Both tests use the
disposable `migrations_test_database_url`, not the shared `pisniar_test`.
"""

from __future__ import annotations

from collections.abc import Awaitable, Callable
from datetime import UTC, datetime

import asyncpg
import pytest
from alembic import command
from sqlalchemy.engine import make_url
from sqlalchemy.exc import IntegrityError

pytestmark = pytest.mark.integration

PREVIOUS_REVISION = "be8d6bff2a6c"
MANUAL_FIELDS_REVISION = "6134b8e293e1"
PREVIEW_HASH_REVISION = "ba0fdb351081"

RunAlembic = Callable[..., Awaitable[None]]


async def test_upgrade_head_then_downgrade_base_then_upgrade_head(
    migrations_test_database_url: str,
    run_alembic: RunAlembic,
) -> None:
    await run_alembic(command.upgrade, "head", database_url=migrations_test_database_url)
    await run_alembic(command.downgrade, "base", database_url=migrations_test_database_url)
    await run_alembic(command.upgrade, "head", database_url=migrations_test_database_url)


async def test_alembic_check_reports_no_drift(
    migrations_test_database_url: str,
    run_alembic: RunAlembic,
) -> None:
    await run_alembic(command.upgrade, "head", database_url=migrations_test_database_url)

    # `command.check` raises `AutogenerateDiffsDetected` on drift, which fails the test with the diff in its message.
    await run_alembic(command.check, database_url=migrations_test_database_url)


async def test_channel_message_kind_backfill_follows_the_publication_rule(
    migrations_test_database_url: str,
    run_alembic: RunAlembic,
) -> None:
    """a preview means the video went out, else a cover means a photo, else text; a post that
    was never published stays NULL, and every touched row gets a fresh `updated_at`."""
    old_stamp = datetime(2020, 1, 1, tzinfo=UTC)
    await run_alembic(command.upgrade, PREVIOUS_REVISION, database_url=migrations_test_database_url)

    plain_dsn = (
        make_url(migrations_test_database_url).set(drivername="postgresql").render_as_string(hide_password=False)
    )
    connection = await asyncpg.connect(plain_dsn)
    try:
        for track_id, cover_url in ((1, "https://cdn.example/a.jpg"), (2, None), (3, "")):
            await connection.execute(
                "INSERT INTO track (id, source_url, source_url_normalized, cover_url) "
                "OVERRIDING SYSTEM VALUE VALUES ($1, $2, $2, $3)",
                track_id,
                f"test://{track_id}",
                cover_url,
            )
        rows = [
            (1, 1, 10, 5),
            (2, 1, 11, None),
            (3, 2, 12, None),
            (4, 3, 13, None),
            (5, 1, None, None),
        ]
        expected_kinds = {1: "video", 2: "photo", 3: "text", 4: "text", 5: None}
        for post_id, track_id, message_id, preview_id in rows:
            await connection.execute(
                "INSERT INTO post (id, track_id, created_by_user_id, channel_chat_id, "
                "channel_message_id, preview_chat_id, preview_message_id, updated_at) "
                "OVERRIDING SYSTEM VALUE VALUES ($1, $2, 1, $3, $4, $5, $6, $7::timestamptz)",
                post_id,
                track_id,
                -100 if message_id else None,
                message_id,
                -200 if preview_id else None,
                preview_id,
                old_stamp,
            )

        await run_alembic(command.upgrade, MANUAL_FIELDS_REVISION, database_url=migrations_test_database_url)

        stored = {
            record["id"]: record
            for record in await connection.fetch(
                "SELECT id, channel_message_kind, updated_at > $1::timestamptz AS touched FROM post",
                old_stamp,
            )
        }
    finally:
        await connection.close()

    for post_id, expected_kind in expected_kinds.items():
        assert stored[post_id]["channel_message_kind"] == expected_kind, post_id
    assert [stored[post_id]["touched"] for post_id in (1, 2, 3, 4)] == [True] * 4
    assert stored[5]["touched"] is False

    await run_alembic(command.downgrade, "-1", database_url=migrations_test_database_url)


async def test_preview_params_hash_backfill_takes_the_newest_render_and_fails_without_one(
    migrations_test_database_url: str,
    run_alembic: RunAlembic,
) -> None:
    """a previewed post gets its newest render's hash and a fresh `updated_at`; a post without a
    preview is untouched; a previewed post with no render row fails the CHECK."""
    old_stamp = datetime(2020, 1, 1, tzinfo=UTC)
    await run_alembic(command.upgrade, MANUAL_FIELDS_REVISION, database_url=migrations_test_database_url)

    plain_dsn = (
        make_url(migrations_test_database_url).set(drivername="postgresql").render_as_string(hide_password=False)
    )
    connection = await asyncpg.connect(plain_dsn)
    try:
        await connection.execute(
            "INSERT INTO track (id, source_url, source_url_normalized) "
            "OVERRIDING SYSTEM VALUE VALUES (1, 'test://1', 'test://1')"
        )
        for post_id, preview_id in ((1, 10), (2, None), (4, 12)):
            await connection.execute(
                "INSERT INTO post (id, track_id, created_by_user_id, preview_chat_id, "
                "preview_message_id, updated_at) OVERRIDING SYSTEM VALUE "
                "VALUES ($1, 1, 1, $2, $3, $4::timestamptz)",
                post_id,
                -200 if preview_id else None,
                preview_id,
                old_stamp,
            )
        renders = (
            (1, "older", 2021),
            (1, "newer", 2022),
            (4, "tie_first", 2021),
            (4, "tie_second", 2021),
        )
        for render_post_id, params_hash, stamp_year in renders:
            await connection.execute(
                "INSERT INTO render (post_id, params_hash, path, size_bytes, duration_ms, "
                "updated_at) VALUES ($1, $2, 'p', 1, 1, $3::timestamptz)",
                render_post_id,
                params_hash,
                datetime(stamp_year, 1, 1, tzinfo=UTC),
            )

        await run_alembic(command.upgrade, PREVIEW_HASH_REVISION, database_url=migrations_test_database_url)

        stored = {
            record["id"]: record
            for record in await connection.fetch(
                "SELECT id, preview_params_hash, updated_at > $1::timestamptz AS touched FROM post",
                old_stamp,
            )
        }
        await run_alembic(command.downgrade, "-1", database_url=migrations_test_database_url)
        column_left = await connection.fetchval(
            "SELECT count(*) FROM information_schema.columns "
            "WHERE table_name = 'post' AND column_name = 'preview_params_hash'"
        )
        check_left = await connection.fetchval(
            "SELECT count(*) FROM pg_constraint WHERE conname = 'ck_post_preview_params_hash_matches_ref'"
        )

        await connection.execute(
            "INSERT INTO post (id, track_id, created_by_user_id, preview_chat_id, "
            "preview_message_id) OVERRIDING SYSTEM VALUE VALUES (3, 1, 1, -200, 11)"
        )
        with pytest.raises(IntegrityError, match="ck_post_preview_params_hash_matches_ref"):
            await run_alembic(command.upgrade, PREVIEW_HASH_REVISION, database_url=migrations_test_database_url)
        # the failed upgrade rolled back: the version table still names the previous revision and the column is absent
        version_after_failure = await connection.fetchval("SELECT version_num FROM alembic_version")
        column_after_failure = await connection.fetchval(
            "SELECT count(*) FROM information_schema.columns "
            "WHERE table_name = 'post' AND column_name = 'preview_params_hash'"
        )
    finally:
        await connection.close()

    assert version_after_failure == MANUAL_FIELDS_REVISION
    assert column_after_failure == 0
    assert stored[1]["preview_params_hash"] == "newer"
    assert stored[1]["touched"] is True
    assert stored[2]["preview_params_hash"] is None
    assert stored[2]["touched"] is False
    assert stored[4]["preview_params_hash"] == "tie_second"
    assert (column_left, check_left) == (0, 0)


async def test_untimed_lines_migration_keeps_the_check_and_downgrade_drops_the_untimed(
    migrations_test_database_url: str,
    run_alembic: RunAlembic,
) -> None:
    """an existing track has no marker; a line without a time may be stored but a negative one
    may not; going back deletes the untimed lines (a NOT NULL column cannot hold them)."""
    await run_alembic(command.upgrade, PREVIEW_HASH_REVISION, database_url=migrations_test_database_url)

    plain_dsn = (
        make_url(migrations_test_database_url).set(drivername="postgresql").render_as_string(hide_password=False)
    )
    connection = await asyncpg.connect(plain_dsn)
    try:
        await connection.execute(
            "INSERT INTO track (id, source_url, source_url_normalized) "
            "OVERRIDING SYSTEM VALUE VALUES (1, 'test://1', 'test://1')"
        )
        await connection.execute(
            "INSERT INTO lyric (track_id, line_index, start_ms, text, source) VALUES (1, 0, 1000, 'timed', 'lrclib')"
        )
        with pytest.raises(asyncpg.NotNullViolationError):
            await connection.execute(
                "INSERT INTO lyric (track_id, line_index, start_ms, text, source) "
                "VALUES (1, 1, NULL, 'untimed', 'manual')"
            )

        await run_alembic(command.upgrade, "head", database_url=migrations_test_database_url)

        marker = await connection.fetchval("SELECT lyrics_edited_at FROM track WHERE id = 1")
        await connection.execute(
            "INSERT INTO lyric (track_id, line_index, start_ms, text, source) VALUES (1, 1, NULL, 'untimed', 'manual')"
        )
        with pytest.raises(asyncpg.CheckViolationError, match="ck_lyric_start_ms_non_negative"):
            await connection.execute(
                "INSERT INTO lyric (track_id, line_index, start_ms, text, source) "
                "VALUES (1, 2, -1, 'negative', 'manual')"
            )

        await run_alembic(command.downgrade, "-1", database_url=migrations_test_database_url)
        kept = await connection.fetch("SELECT text FROM lyric ORDER BY line_index")
        marker_columns = await connection.fetchval(
            "SELECT count(*) FROM information_schema.columns "
            "WHERE table_name = 'track' AND column_name = 'lyrics_edited_at'"
        )
        start_ms_nullable = await connection.fetchval(
            "SELECT is_nullable FROM information_schema.columns WHERE table_name = 'lyric' AND column_name = 'start_ms'"
        )

        await run_alembic(command.upgrade, "head", database_url=migrations_test_database_url)
    finally:
        await connection.close()

    assert marker is None
    assert [record["text"] for record in kept] == ["timed"]
    assert marker_columns == 0
    assert start_ms_nullable == "NO"
